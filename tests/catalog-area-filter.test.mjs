import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { catalogPreferenceKey, parseSameAreaPreference } from "../src/lib/catalogPreferences.ts";
import { getSettingsGroups } from "../src/lib/settingsMenu.ts";

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const migration = read("supabase/migrations/20261012050435_catalog_same_area_filter.sql");
const first = "00000000-0000-4000-8000-000000000001";
const second = "00000000-0000-4000-8000-000000000002";
const third = "00000000-0000-4000-8000-000000000003";

test("same-area discovery filters before pagination, authenticates area ownership, keeps all-area RPC intact", async () => {
  const db = new PGlite();
  try {
    // Numeric distance stand-ins test filtering/cursors, not PostGIS geometry.
    await db.exec(`create role anon; create role authenticated;
      create schema auth; create schema private; create schema extensions;
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid',true),'')::uuid $$;
      create domain extensions.geography as text;
      create function extensions.st_makepoint(double precision,double precision) returns text language sql as $$ select $1::text $$;
      create function extensions.st_setsrid(text,integer) returns text language sql as $$ select $1 $$;
      create function extensions.st_distance(extensions.geography,extensions.geography) returns double precision language sql as $$ select abs($1::double precision-$2::double precision)*1000 $$;
      create table public.user_locations(user_id uuid primary key,subdistrict_code text,geography extensions.geography);
      create table public.markets(market_id bigint primary key,name text,description text,image_url text,geography extensions.geography,approval_status text,subdistrict_code text);
      create table public.stores(store_id bigint primary key,market_id bigint,name text,description text,image_url text,product_name text,approval_status text);
      create table public.seller_listings(store_id bigint,stock_quantity integer,reserved_quantity integer,status text);
      grant usage on schema public,private,auth,extensions to anon,authenticated;
      alter table public.user_locations enable row level security;
      create policy self_location on public.user_locations for select to authenticated using(user_id=(select auth.uid()));
      grant select on public.user_locations to authenticated;
      insert into public.user_locations values('${first}','A','0'),('${second}','B','0');
      insert into public.markets select n,'Outside '||n,'','',n::text,'approved','B' from generate_series(1,30) n;
      insert into public.markets values(100,'Local market','','','100','approved','A'),(101,'Local second','','','101','approved','A'),(102,'Pending','','','0','pending','A');
      insert into public.stores values(1,100,'Local store','','','Product','approved'),(2,100,'Suspended','','','Hidden','suspended'),(3,101,'Other local','','','Other','approved'),(4,102,'Pending parent','','','Hidden','approved');
      insert into public.seller_listings values(1,10,2,'active'),(1,90,0,'paused'),(2,70,0,'active'),(3,5,0,'active');`);
    const oldDiscovery = read("supabase/migrations/20261003021710_show_all_catalog_and_chat_partner.sql").split("-- Profiles are private")[0];
    await db.exec(oldDiscovery);
    await db.exec(migration);
    await db.exec("set role anon");
    assert.equal((await db.query("select * from public.discover_catalog_page(p_limit=>1)")).rows.length, 1);
    await assert.rejects(db.query("select * from public.discover_same_area_catalog_page()"), /permission denied/);
    await assert.rejects(db.query("select * from private.discover_same_area_catalog_page()"), /permission denied/);
    await db.exec("reset role; set role authenticated");
    const setUser = (id) => db.query("select set_config('test.uid',$1,false)", [id]);
    await setUser(first);
    await assert.rejects(db.query("select * from public.stores"), /permission denied/);
    assert.equal((await db.query("select count(*)::int n from public.user_locations")).rows[0].n, 1);
    const getPage = (after) => db.query("select * from public.discover_same_area_catalog_page(p_limit=>2,p_after_distance_km=>$1,p_after_entity_type=>$2,p_after_entity_id=>$3)", after ? [after.distance_km, after.entity_type, after.entity_id] : [null,null,null]);
    const one = (await getPage()).rows;
    assert.equal(one.length, 2);
    assert.ok(one.every((row) => row.market_id === 100));
    assert.ok(one.every((row) => Number(row.distance_km) > 10));
    assert.equal(Number(one[0].available_stock), 8);
    const two = (await getPage(one.at(-1))).rows;
    assert.equal(two.length, 2);
    assert.ok(two.every((row) => row.market_id === 101));
    assert.equal((await getPage(two.at(-1))).rows.length, 0);
    const merged = [...one,...two];
    assert.equal(new Set(merged.map((row) => `${row.entity_type}:${row.entity_id}`)).size, 4);
    assert.deepEqual(Object.keys(merged[0]).sort(), ["entity_type","entity_id","market_id","name","description","image_url","distance_km","radius_km","available_stock"].sort());
    assert.equal((await db.query("select * from public.discover_same_area_catalog_page(p_kind=>'market')")).rows.length, 2);
    assert.equal((await db.query("select * from public.discover_same_area_catalog_page(p_query=>'Product')")).rows.length, 1);
    assert.equal((await db.query("select * from public.discover_catalog_page(p_limit=>100)")).rows.length, 34);
    await setUser(second);
    const other = (await db.query("select * from public.discover_same_area_catalog_page(p_limit=>100)")).rows;
    assert.equal(other.length, 30);
    assert.ok(other.every((row) => row.market_id < 100));
    await setUser(third);
    assert.equal((await db.query("select * from public.discover_same_area_catalog_page()")).rows.length, 0);
    await setUser("");
    assert.equal((await db.query("select * from private.discover_same_area_catalog_page()")).rows.length, 0);
    await db.exec("reset role");
    await db.query("update public.user_locations set subdistrict_code='B' where user_id=$1", [first]);
    await db.exec("set role authenticated");
    await setUser(first);
    assert.ok((await db.query("select * from public.discover_same_area_catalog_page()")).rows.every((row) => row.market_id < 100));
  } finally { await db.close(); }
});

test("area preference defaults to all, is account scoped, and renamed setting route/menu are wired", () => {
  for (const value of [null,"false","","garbage","TRUE"]) assert.equal(parseSameAreaPreference(value), false);
  assert.equal(parseSameAreaPreference("true"), true);
  assert.notEqual(catalogPreferenceKey(first), catalogPreferenceKey(second));
  const groups = getSettingsGroups({ isAdmin: false, isMarketOwner: false, isStoreManager: false, isSeller: false });
  assert.ok(groups.find((group) => group.title === "พื้นที่และการจัดส่ง").actions.some((action) => action.route === "/settings/catalog"));
  assert.ok(!existsSync(new URL("../app/(tabs)/profile.tsx", import.meta.url)));
  assert.match(read("app/(tabs)/_layout.tsx"), /name="setting"/);
  assert.match(read("app/(tabs)/setting.tsx"), /<Text style={styles.pageTitle}>ตั้งค่า<\/Text>/);
  const context = read("src/context/CatalogPreferencesContext.tsx");
  assert.match(context, /result\?\.userId === userId/);
  assert.match(context, /if \(active\) setResult/);
  assert.match(context, /current\?\.userId === userId/);
  assert.match(read("app/_layout.tsx"), /<AuthProvider><CatalogPreferencesProvider>/);
  assert.match(read("app/(tabs)/index.tsx"), /enabled: preferencesReady/);
  assert.match(read("src/hooks/useCommerce.ts"), /pageResult\?\.scope === scope/);
  assert.match(read("app/settings/catalog.tsx"), /ยังไม่ได้ตั้งพื้นที่หลัก/);
  assert.doesNotMatch(migration, /p_user_id|p_subdistrict_code/);
});
