import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { translateDatabaseError } from "../src/lib/databaseError.ts";
const read = (path) => readFileSync(new URL(`../${path}`,import.meta.url),"utf8");
const sql = read("supabase/migrations/20261015120640_backend_consistency_security_hardening.sql");
const buyer="00000000-0000-4000-8000-000000000001";
const seller="00000000-0000-4000-8000-000000000002";
const other="00000000-0000-4000-8000-000000000003";
const owner="00000000-0000-4000-8000-000000000004";
const outsider="00000000-0000-4000-8000-000000000005";

test("backend hardening isolates sellers, serializes shipping, rejects NaN, enforces contact and bounded business limits", async () => {
  const db=new PGlite();
  const uid=(value)=>db.query("select set_config('test.uid',$1,false)",[value]);
  try{
    await db.exec(`
      create role anon;create role authenticated;create role service_role;
      create schema auth;create schema private;
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid',true),'')::uuid $$;
      create function private.is_admin() returns boolean language sql stable as $$ select current_setting('test.admin',true)='yes' $$;
      create table profiles(user_id uuid primary key,phone_num text);
      create table markets(market_id bigint primary key,owner_id uuid,name text,hub_address text);
      create table stores(store_id bigint primary key,manager_id uuid,name text,image_url text,unit_price numeric(12,2) check(unit_price>0));
      create table orders(order_id bigint generated by default as identity primary key,buyer_id uuid,address_id bigint,
        market_id bigint,total_amount numeric(12,2) default 10,fulfillment_method text default 'delivery',status text default 'awaiting_preparation',
        order_number text default 'LM-test',tracking_number text,courier_name text,shipped_at timestamptz,created_at timestamptz default now(),updated_at timestamptz default now());
      create table order_items(order_item_id bigint primary key,order_id bigint,store_id bigint,
        product_name text,product_image_url text,unit text,unit_price numeric,total_amount numeric);
      create table order_allocations(allocation_id bigint primary key,order_item_id bigint,seller_id uuid,quantity integer,
        status text,stock_deducted_at timestamptz,created_at timestamptz default now());
      create table demo_accounts(wallet_balance numeric,seller_pending numeric,seller_settled numeric);
      create table demo_topup_requests(request_id uuid primary key,user_id uuid,amount numeric,status text default 'pending');
      create table demo_ledger(wallet_delta numeric,seller_delta numeric);
      create table demo_settlements(amount numeric);
      create table chat_messages(room_id bigint,sender_id uuid,message text,created_at timestamptz default now());
      create table store_seller_applications(applicant_id uuid);
      create function private.market_owner(mid bigint) returns boolean language sql stable security definer as $$
        select exists(select 1 from public.markets where market_id=mid and owner_id=auth.uid()) $$;
      create function private.store_manager(sid bigint) returns boolean language sql stable security definer as $$
        select exists(select 1 from public.stores where store_id=sid and manager_id=auth.uid()) $$;
      insert into profiles values('${buyer}','0812345678'),('${seller}','0812345678'),('${other}','0812345678'),('${owner}','0812345678'),('${outsider}',null);
      insert into markets values(1,'${owner}','Market','Hub');
      insert into stores values(100,'${seller}','Own',null,100),(200,'${other}','Other',null,200);
      insert into orders(order_id,buyer_id,address_id,market_id,status) values(1,'${buyer}',999,1,'at_hub'),(2,'${buyer}',999,1,'cancelled');
      insert into order_items values(10,1,100,'Own',null,'ชิ้น',100,100),(20,1,200,'Other',null,'ชิ้น',200,200);
      insert into order_allocations values(1,10,'${seller}',1,'at_hub',now(),now()),(2,20,'${other}',1,'at_hub',now(),now());
      alter table orders enable row level security;
      create policy orders_participants on orders for select to authenticated using(false);
      alter table order_items enable row level security;
      grant usage on schema public,private,auth to anon,authenticated;
      grant select on orders,order_items to authenticated;
    `);
    await db.exec(sql);
    await db.exec("drop policy orders_participants on orders;create policy orders_participants on orders for select to authenticated using(private.can_access_order(order_id))");
    await uid(seller);await db.exec("set role authenticated");
    assert.equal((await db.query("select count(*)::int n from orders")).rows[0].n,0,"seller cannot select buyer/total/address header");
    assert.deepEqual((await db.query("select order_item_id from order_items")).rows,[],"seller uses minimal DTO, not full line-item quantities");
    const own=(await db.query("select public.get_my_seller_allocations() dto")).rows[0].dto;
    assert.equal(own.length,1);
    assert.equal(own[0].order_items.orders.order_number,"LM-test");
    for(const forbidden of ["buyer_id","address_id","total_amount","tracking_number"]) {
      assert.ok(!(forbidden in own[0].order_items.orders));
    }
    assert.deepEqual((await db.query("select public.get_my_seller_allocations(2) dto")).rows[0].dto,[]);
    await uid(outsider);
    assert.equal((await db.query("select count(*)::int n from order_items")).rows[0].n,0);
    assert.deepEqual((await db.query("select public.get_my_seller_allocations() dto")).rows[0].dto,[]);
    await uid(buyer);
    assert.equal((await db.query("select count(*)::int n from order_items")).rows[0].n,2);
    await assert.rejects(db.query("select public.ship_order(1,'X','C')"),/forbidden/);
    await uid(owner);
    await db.query("select public.consolidate_order(1)");
    await db.query("select public.consolidate_order(1)");
    await db.query("select public.ship_order(1,'TRACK','COURIER')");
    await db.query("select public.ship_order(1,'TRACK','COURIER')");
    await assert.rejects(db.query("select public.ship_order(1,'CHANGED','COURIER')"),/already recorded/);
    await assert.rejects(db.query("select public.consolidate_order(2)"),/invalid order transition/);
    await db.exec("reset role;update orders set status='delivered' where order_id=1;set role authenticated");
    await db.query("select public.consolidate_order(1)");
    await db.query("select public.ship_order(1,'TRACK','COURIER')");
    assert.equal((await db.query("select status from orders where order_id=1")).rows[0].status,"delivered","retry never regresses state");
    await db.exec("set role anon");
    await assert.rejects(db.query("select public.ship_order(1,'X','C')"),/permission denied/);
    await assert.rejects(db.query("select public.get_my_seller_allocations()"),/permission denied/);
    await db.exec("reset role");
    for(const [table,column] of [["stores","unit_price"],["orders","total_amount"],["demo_accounts","wallet_balance"],["demo_ledger","wallet_delta"]]) {
      const command=table==="stores" ? "update stores set unit_price='NaN' where store_id=100" : `insert into ${table}(${column}) values('NaN')`;
      await uid("");
      await assert.rejects(db.exec(command),/_finite/);
    }
    // OAuth/incomplete legacy accounts remain readable; new business actions need contact.
    await uid(outsider);
    await assert.rejects(db.query("insert into orders(order_id,buyer_id,market_id) values(100,$1,1)",[outsider]),/valid mobile contact required/);
    await db.query("update profiles set phone_num='0812345678' where user_id=$1",[outsider]);
    for(let n=100;n<105;n++)await db.query("insert into orders(order_id,buyer_id,market_id) values($1,$2,1)",[n,outsider]);
    await assert.rejects(db.query("insert into orders(order_id,buyer_id,market_id) values(105,$1,1)",[outsider]),/action rate limit/);
    assert.equal((await db.query("select attempts from private.business_action_limits where user_id=$1 and action='orders'",[outsider])).rows[0].attempts,5,"failed quota rolls back");
    await db.exec("update private.business_action_limits set window_started_at=now()-interval '2 minutes'");
    for(let n=105;n<110;n++)await db.query("insert into orders(order_id,buyer_id,market_id) values($1,$2,1)",[n,outsider]);
    await db.exec("update private.business_action_limits set window_started_at=now()-interval '2 minutes'");
    await assert.rejects(db.query("insert into orders(order_id,buyer_id,market_id) values(110,$1,1)",[outsider]),/too many pending orders/);
    assert.equal((await db.query("select count(*)::int n from orders where buyer_id=$1",[outsider])).rows[0].n,10);
    await db.query("update orders set status='cancelled' where order_id=100");
    await db.query("insert into orders(order_id,buyer_id,market_id) values(110,$1,1)",[outsider]);
    for(let n=1;n<=3;n++) await db.query("insert into demo_topup_requests(request_id,user_id,amount) values($1,$2,100)",[`10000000-0000-4000-8000-${String(n).padStart(12,"0")}`,outsider]);
    await db.exec("update private.business_action_limits set window_started_at=now()-interval '2 minutes'");
    await assert.rejects(db.query("insert into demo_topup_requests(request_id,user_id,amount) values('10000000-0000-4000-8000-000000000004',$1,100)",[outsider]),/too many pending topups/);
    await db.query("insert into demo_topup_requests(request_id,user_id,amount) values('10000000-0000-4000-8000-000000000001',$1,100) on conflict do nothing",[outsider]);
    for(let n=0;n<30;n++)await db.query("insert into chat_messages(room_id,sender_id,message,created_at) values(1,$1,'hello','2099-01-01')",[outsider]);
    await assert.rejects(db.query("insert into chat_messages(room_id,sender_id,message) values(1,$1,'spam')",[outsider]),/action rate limit/);
    assert.equal((await db.query("select count(*)::int n from chat_messages where created_at>'2090-01-01'")).rows[0].n,0,"server owns timestamp");
    await db.exec("set role authenticated");
    await assert.rejects(db.query("select private.consume_business_limit('fake',9999,1)"),/permission denied/);
    await assert.rejects(db.query("select * from private.business_action_limits"),/permission denied/);
  }finally{await db.close();}
});

test("frontend uses seller DTO and translates new business guards; filters stay compact",()=>{
  for(const path of ["src/hooks/useCommerce.ts","app/seller/allocations/[id].tsx"])assert.match(read(path),/rpc\("get_my_seller_allocations(?:_page)?"/);
  for(const message of ["valid mobile contact required","too many pending orders","too many pending topups","action rate limit exceeded","stores_unit_price_finite","invalid order transition"]) {
    assert.notEqual(translateDatabaseError({message}),"ดำเนินการไม่สำเร็จ กรุณาลองใหม่อีกครั้ง");
  }
  const filters=read("src/components/HomeCatalogFilters.tsx");
  assert.match(filters,/<ScrollView horizontal/);
  assert.match(filters,/<Modal visible=\{open\}/);
  assert.match(filters,/onChange\(draft\); setOpen\(false\)/);
  assert.match(filters,/setDraft\(value\)/);
  assert.match(read("app/(tabs)/index.tsx"),/<HomeCatalogFilters/);
  assert.doesNotMatch(read("app/(tabs)/index.tsx"),/<SearchableDropdown label="เรียงตาม"/);
});
